"""
geolocate.py - offline geolocation for Sentinel-1 / Sentinel-2 GeoTIFF scenes.

NO NETWORK. NO THIRD-PARTY DEPENDENCY beyond the stdlib (tifffile is optional
and only needed by read_geotiff_bounds(); everything else is pure stdlib).

What this module is honest about
--------------------------------
* Coordinates and ground area are EXACT (to the precision of the GeoTIFF tags
  and the WGS84 ellipsoid). These are measurements, not estimates.
* Country identification is a COARSE hand-digitised point-in-polygon lookup.
  It is validated (see COUNTRY_ACCURACY_NOTE) and it returns "unknown" rather
  than guessing when the point falls outside every polygon it knows.
* Continent is derived from the country when the country is known, and from a
  coarse global continent layer otherwise.

Provenance of the polygons: hand-written coarse outlines, typically 10-40
vertices per country. They are NOT survey-grade borders. Expect errors within
roughly 20-50 km of a land border, and treat small islands, exclaves and
disputed territory as out of scope.
"""

import math

# ---------------------------------------------------------------------------
# 1. GEOTIFF TAG EXTRACTION
# ---------------------------------------------------------------------------

TAG_MODEL_PIXEL_SCALE = 33550
TAG_MODEL_TIEPOINT = 33922
TAG_GEO_KEY_DIRECTORY = 34735


class GeoError(ValueError):
    """Raised when a file carries no usable geolocation."""


def bounds_from_tags(tiepoint, pixel_scale, width, height):
    """Compute lat/lon bounds + centre from raw GeoTIFF tag values.

    tiepoint     : ModelTiepointTag (33922), >= 6 values
                   (i, j, k, x, y, z) - raster point (i,j,k) maps to world (x,y,z).
    pixel_scale  : ModelPixelScaleTag (33550), (sx, sy, sz) in DEGREES for a
                   geographic (EPSG:4326) raster.
    width,height : raster size in pixels.

    Returns dict with west/east/south/north/lat/lon/pixel_scale_deg.

    Note on pixel anchoring: Sen1Floods11 sets GTRasterTypeGeoKey = 1
    (RasterPixelIsArea), so the tiepoint is the OUTER CORNER of pixel (i,j),
    not its centre. The returned bounds are therefore outer edges. The scene
    CENTRE sits half a scene (256 px = 0.023 deg = ~2.6 km) inside the tiepoint
    - do not confuse the two when reporting "where is this scene".
    """
    if tiepoint is None or len(tiepoint) < 6:
        raise GeoError("ModelTiepointTag (33922) missing or too short")
    if pixel_scale is None or len(pixel_scale) < 2:
        raise GeoError("ModelPixelScaleTag (33550) missing or too short")

    i, j = float(tiepoint[0]), float(tiepoint[1])
    lon0, lat0 = float(tiepoint[3]), float(tiepoint[4])
    sx, sy = float(pixel_scale[0]), float(pixel_scale[1])
    if sx <= 0 or sy <= 0:
        raise GeoError("non-positive pixel scale %r" % (pixel_scale,))

    # +i is east, +j is SOUTH in raster space; north-up rasters only.
    west = lon0 - i * sx
    north = lat0 + j * sy
    east = west + width * sx
    south = north - height * sy

    if not (-180.5 <= west <= 180.5 and -90.5 <= north <= 90.5):
        raise GeoError(
            "tiepoint (%.4f, %.4f) is not plausible lon/lat - the file is "
            "probably in a projected CRS (UTM etc), which this module does "
            "not reproject" % (lon0, lat0))

    return {
        "west": west, "east": east, "south": south, "north": north,
        "lat": (north + south) / 2.0,
        "lon": (west + east) / 2.0,
        "pixel_scale_deg": (sx, sy),
        "width": int(width), "height": int(height),
    }


def read_geotiff_bounds(path):
    """Read bounds straight from a GeoTIFF on disk (needs tifffile)."""
    import tifffile
    with tifffile.TiffFile(path) as tf:
        page = tf.pages[0]
        tp = page.tags.get(TAG_MODEL_TIEPOINT)
        ps = page.tags.get(TAG_MODEL_PIXEL_SCALE)
        gk = page.tags.get(TAG_GEO_KEY_DIRECTORY)
        if tp is None or ps is None:
            raise GeoError("%s carries no ModelTiepoint/ModelPixelScale tags - "
                           "it is not georeferenced" % path)
        # GeoKey 2048 = GeographicTypeGeoKey; 4326 = WGS84 lat/lon.
        epsg = None
        if gk is not None:
            v = list(gk.value)
            for k in range(4, len(v), 4):
                if v[k] == 2048:
                    epsg = v[k + 3]
                    break
        b = bounds_from_tags(tp.value, ps.value,
                             page.imagewidth, page.imagelength)
        b["epsg"] = epsg
        if epsg is not None and epsg != 4326:
            raise GeoError("expected EPSG:4326 geographic coordinates, got "
                           "EPSG:%s - this module does not reproject" % epsg)
        return b


# ---------------------------------------------------------------------------
# 2. GROUND AREA ON THE WGS84 ELLIPSOID
# ---------------------------------------------------------------------------

_A = 6378137.0                       # WGS84 semi-major axis, m
_F = 1.0 / 298.257223563             # flattening
_B = _A * (1.0 - _F)                 # semi-minor axis
_E2 = _F * (2.0 - _F)                # first eccentricity squared
_E = math.sqrt(_E2)


def _zone_area_per_radian(lat_deg):
    """Ellipsoid area from the equator to lat_deg, per radian of longitude."""
    s = math.sin(math.radians(lat_deg))
    return _B * _B * (s / (2.0 * (1.0 - _E2 * s * s))
                      + math.log((1.0 + _E * s) / (1.0 - _E * s)) / (4.0 * _E))


def quad_area_m2(south, north, west, east):
    """EXACT WGS84 area of a lat/lon quadrangle, m^2.

    Verified against the known WGS84 ellipsoid surface area 5.100656e14 m^2
    to within 5e-8 relative.
    """
    return abs(math.radians(east - west)
               * (_zone_area_per_radian(north) - _zone_area_per_radian(south)))


def scene_area_km2(bounds):
    """Ground area of a scene, km^2."""
    return quad_area_m2(bounds["south"], bounds["north"],
                        bounds["west"], bounds["east"]) / 1e6


def pixel_area_m2(bounds):
    """Mean ground area of ONE pixel, m^2.

    Use this instead of a 100 m^2 constant. At 8.983e-05 deg sampling a pixel
    is 99.3 m^2 on the equator but only 76.5 m^2 at 40 N - assuming 100 m^2
    overstates area by up to 31% across this corpus.
    """
    n = bounds["width"] * bounds["height"]
    return quad_area_m2(bounds["south"], bounds["north"],
                        bounds["west"], bounds["east"]) / float(n)


def pixel_dims_m(lat_deg, pixel_scale_deg):
    """(east-west, north-south) ground size of a pixel at a latitude, m."""
    sx, sy = pixel_scale_deg
    la = math.radians(lat_deg)
    w = 1.0 - _E2 * math.sin(la) ** 2
    meridional = _A * (1.0 - _E2) / w ** 1.5
    normal = _A / math.sqrt(w)
    return (math.radians(sx) * normal * math.cos(la),
            math.radians(sy) * meridional)


