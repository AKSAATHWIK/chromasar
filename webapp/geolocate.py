def _parse(s):
    return [tuple(float(v) for v in pair.split(","))
            for pair in s.split()]


_COUNTRY_POLYS = []
for _name, _cont, _prio, _wkt in _COUNTRIES:
    _ring = _parse(_wkt)
    _lons = [p[0] for p in _ring]
    _lats = [p[1] for p in _ring]
    _COUNTRY_POLYS.append({
        "name": _name, "continent": _cont, "prio": _prio, "ring": _ring,
        "bbox": (min(_lons), min(_lats), max(_lons), max(_lats)),
    })
